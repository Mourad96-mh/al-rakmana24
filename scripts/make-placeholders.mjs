/**
 * Generates the on-brand placeholder images used until the newsroom uploads real
 * photography through the admin dashboard.
 *
 * They are deliberately NOT stock photos: flat red/black/white geometry built on
 * the logo's chevron motif, so a page full of them reads as "art direction
 * pending" rather than as a broken layout. Every one is replaceable from
 * /admin without touching code — components resolve images through
 * `resolveMedia()` in lib/media.ts, which falls back here only when a Payload
 * Media document is absent.
 *
 * Run: node scripts/make-placeholders.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const OUT = path.resolve(process.cwd(), 'public/placeholders')

const RED = '#d92415'
const BLACK = '#0a0a0a'
const WHITE = '#ffffff'

/** Nine variants so a dense homepage does not show the same tile twice. */
const VARIANTS = [
  { id: 'a', bg: BLACK, fg: RED, accent: WHITE, motif: 'chevrons' },
  { id: 'b', bg: RED, fg: WHITE, accent: BLACK, motif: 'grid' },
  { id: 'c', bg: WHITE, fg: BLACK, accent: RED, motif: 'chevrons' },
  { id: 'd', bg: BLACK, fg: WHITE, accent: RED, motif: 'bars' },
  { id: 'e', bg: RED, fg: BLACK, accent: WHITE, motif: 'rings' },
  { id: 'f', bg: WHITE, fg: RED, accent: BLACK, motif: 'bars' },
  { id: 'g', bg: BLACK, fg: RED, accent: WHITE, motif: 'rings' },
  { id: 'h', bg: WHITE, fg: BLACK, accent: RED, motif: 'grid' },
  { id: 'i', bg: RED, fg: WHITE, accent: BLACK, motif: 'chevrons' },
]

const SIZES = [
  { name: 'feature', w: 1200, h: 675 },
  { name: 'card', w: 768, h: 512 },
  { name: 'thumb', w: 400, h: 300 },
]

function motifMarkup(motif, w, h, fg, accent) {
  const cx = w / 2
  const cy = h / 2
  const u = Math.min(w, h) / 10

  switch (motif) {
    case 'chevrons': {
      // The logo mark: < > facing each other.
      const s = u * 2
      const sw = Math.max(3, u * 0.34)
      return `
        <path d="M ${cx - s * 0.55} ${cy - s} L ${cx - s * 1.35} ${cy} L ${cx - s * 0.55} ${cy + s}"
              fill="none" stroke="${fg}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round"/>
        <path d="M ${cx + s * 0.55} ${cy - s} L ${cx + s * 1.35} ${cy} L ${cx + s * 0.55} ${cy + s}"
              fill="none" stroke="${accent}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round"/>
      `
    }
    case 'grid': {
      let out = ''
      for (let i = 1; i < 8; i += 1) {
        out += `<line x1="${(w / 8) * i}" y1="0" x2="${(w / 8) * i}" y2="${h}" stroke="${fg}" stroke-width="1.5" opacity="0.35"/>`
      }
      for (let i = 1; i < 5; i += 1) {
        out += `<line x1="0" y1="${(h / 5) * i}" x2="${w}" y2="${(h / 5) * i}" stroke="${fg}" stroke-width="1.5" opacity="0.35"/>`
      }
      out += `<rect x="${cx - u * 1.6}" y="${cy - u * 1.6}" width="${u * 3.2}" height="${u * 3.2}" fill="${accent}"/>`
      return out
    }
    case 'bars': {
      let out = ''
      const n = 6
      for (let i = 0; i < n; i += 1) {
        const bh = u * (1 + ((i * 1.7) % 4))
        out += `<rect x="${cx - u * 4.5 + i * u * 1.6}" y="${cy + u * 2.5 - bh}" width="${u}" height="${bh}" fill="${i % 3 === 0 ? accent : fg}"/>`
      }
      return out
    }
    case 'rings':
    default: {
      return `
        <circle cx="${cx}" cy="${cy}" r="${u * 3}" fill="none" stroke="${fg}" stroke-width="${u * 0.3}"/>
        <circle cx="${cx}" cy="${cy}" r="${u * 1.8}" fill="none" stroke="${accent}" stroke-width="${u * 0.3}"/>
        <circle cx="${cx}" cy="${cy}" r="${u * 0.6}" fill="${accent}"/>
      `
    }
  }
}

function svg({ w, h, bg, fg, accent, motif }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${bg}"/>
  ${motifMarkup(motif, w, h, fg, accent)}
</svg>`
}

async function main() {
  await mkdir(OUT, { recursive: true })
  let count = 0

  for (const v of VARIANTS) {
    for (const s of SIZES) {
      const buf = Buffer.from(svg({ w: s.w, h: s.h, ...v }))
      const file = path.join(OUT, `${v.id}-${s.name}.jpg`)
      await sharp(buf).jpeg({ quality: 82, mozjpeg: true }).toFile(file)
      count += 1
    }
  }

  // A neutral 1200x630 share image so OG tags are never empty before Lot 7.
  const og = Buffer.from(
    svg({ w: 1200, h: 630, bg: BLACK, fg: RED, accent: WHITE, motif: 'chevrons' }),
  )
  await sharp(og).jpeg({ quality: 86, mozjpeg: true }).toFile(path.join(OUT, 'og-default.jpg'))
  count += 1

  await writeFile(
    path.join(OUT, 'README.md'),
    '# Placeholders\n\nGenerated by `node scripts/make-placeholders.mjs`.\n' +
      'Temporary art direction — replaced by real uploads from /admin.\n' +
      'Do not edit by hand; edit the script and regenerate.\n',
  )

  console.log(`wrote ${count} placeholder images to public/placeholders/`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
